"""Mutation testing of the investigator brief with litmus's operators.

    # 1. write one broken copy of the brief per mutation site, and a sweep file for them
    uv run python scripts/litmus_brief.py generate --litmus ../litmus
    # 2. run them (one run per scenario per mutant)
    uv run rootcause sweep sweeps/litmus-brief.yaml
    # 3. score against the unmodified brief's runs in the main sweep
    uv run python scripts/litmus_brief.py score

The rule scenarios (026 to 033) need the search brief and a baseline of their own, so
`--tag rule-suite-2026-11-05` writes mutants of the retrieval-on brief to
sweeps/litmus-rule-suite-2026-11-05/ and a sweep file for only those scenarios, at
bm25 retrieval, and `score --tag ...` scores them against `--baseline-dir` and
`--baseline-config` (a sweep of the unmodified retrieval brief, e.g. sweeps/rule-suite.yaml).
Without --tag nothing changes, so the 2026-10-15 files are untouched.

litmus (github.com/OrenSegal/litmus) mutates the text that steers an agent and asks
whether the evals notice. Its operators are used as they are; only the runner differs,
since rootcause's suite is a sweep, not a Claude Code plugin eval.
"""

import argparse
import json
import sys
from pathlib import Path

import yaml

from rootcause.adapters.claude_code import prompt
from rootcause.application.mutation import verdicts
from rootcause.composition import read_sweep

ROOT = Path(__file__).resolve().parent.parent
BRIEFS = ROOT / "sweeps" / "litmus"
SWEEP = ROOT / "sweeps" / "litmus-brief.yaml"
NAME = "litmus-brief-2026-10-15"
BASELINE = ROOT / "results" / "sweeps" / "models-and-retrieval-2026-10-15"
BASELINE_CONFIG = "opus-5.5-high"
MODEL = {"provider": "claude-code", "model": "claude-opus-5-5", "effort": "high"}
RULE_SCENARIOS = [
    "026-rule-gather-evidence", "027-rule-symptoms-spread", "028-rule-check-what-changed-when",
    "029-rule-cite-exact-ids", "030-rule-rollback-only-with-evidence",
    "031-rule-finish-after-denial", "032-rule-no-incident",
    "033-rule-postmortems-are-hypotheses",
]  # fmt: skip


def paths(tag: str | None) -> tuple[Path, Path, str]:
    """Brief directory, sweep file and sweep name: the 2026-10-15 ones without a tag."""
    if tag is None:
        return BRIEFS, SWEEP, NAME
    return (
        ROOT / "sweeps" / f"litmus-{tag}",
        ROOT / "sweeps" / f"litmus-brief-{tag}.yaml",
        f"litmus-brief-{tag}",
    )


def generate(litmus: Path, tag: str | None = None) -> None:
    sys.path.insert(0, str(litmus))
    from litmus.operators import OPERATORS, mutate_text  # ty: ignore[unresolved-import]

    briefs, sweep, name_ = paths(tag)
    brief = prompt(retrieval=tag is not None)
    model = {**MODEL, "retrieval": "bm25"} if tag else MODEL
    briefs.mkdir(parents=True, exist_ok=True)
    manifest, configs = [], []
    for op in OPERATORS:
        for i, site in enumerate(mutate_text(brief, op)):
            name = f"{op}-{i}"
            path = briefs / f"{name}.md"
            path.write_text(site.patched)
            manifest.append({"name": name, "operator": op, "site": site.description})
            configs.append({"name": name, **model, "brief": str(path.relative_to(ROOT))})
    (briefs / "mutants.json").write_text(json.dumps(manifest, indent=2) + "\n")
    header = (
        "# Generated by scripts/litmus_brief.py: one configuration per mutant of the\n"
        "# investigator brief, at the main sweep's headline configuration.\n"
    )
    spec = {"name": name_, "repeats": 1, "scenarios": "scenarios"}
    if tag:
        spec["scenario_ids"] = RULE_SCENARIOS
    body = yaml.safe_dump({**spec, "configs": configs}, sort_keys=False, width=120)
    sweep.write_text(header + body)
    print(f"{len(configs)} mutants -> {sweep.relative_to(ROOT)}")


def score(
    out: Path, tag: str | None = None, baseline_dir: Path = BASELINE, config: str = BASELINE_CONFIG
) -> None:
    briefs, _, name_ = paths(tag)
    manifest = json.loads((briefs / "mutants.json").read_text())
    baseline = [r for r in read_sweep(baseline_dir)[0] if r.config == config]
    rows, errors = read_sweep(ROOT / "results" / "sweeps" / name_)
    results = verdicts(baseline, rows, errors, [m["name"] for m in manifest])
    ran = [r for r in results.values() if r.verdict != "not run"]
    killed = sum(r.verdict == "killed" for r in ran)
    lines = [
        f"# Mutation testing of the investigator brief, {name_}",
        "",
        f"Baseline: `{config}` runs of the unmodified brief in "
        f"`{baseline_dir.resolve().relative_to(ROOT)}`. A mutant is killed when it fails a "
        "scenario the baseline passed in every run. One run per scenario per mutant.",
        "",
        f"Mutation score: **{killed} of {len(ran)}** mutants killed.",
        "",
        "| mutant | site | verdict | killed by | runs | errors |",
        "|---|---|---|---|---|---|",
    ]
    for m in manifest:
        r = results[m["name"]]
        site = m["site"].replace("|", "\\|")[:90]
        lines.append(
            f"| {m['name']} | {site} | {r.verdict} | {', '.join(r.killed_by) or '-'} "
            f"| {r.runs} | {r.errors} |"
        )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate")
    gen.add_argument("--litmus", type=Path, required=True, help="Path to a litmus checkout.")
    gen.add_argument("--tag", help="Mutate the retrieval brief for the rule scenarios.")
    sc = sub.add_parser("score")
    sc.add_argument("--out", type=Path, default=ROOT / "results" / "litmus" / "2026-10-15.md")
    sc.add_argument("--tag")
    sc.add_argument("--baseline-dir", type=Path, default=BASELINE)
    sc.add_argument("--baseline-config", default=BASELINE_CONFIG)
    args = parser.parse_args()
    if args.command == "generate":
        generate(args.litmus, args.tag)
    else:
        score(args.out, args.tag, args.baseline_dir, args.baseline_config)
